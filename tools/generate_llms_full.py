"""Build wiki/llms-full.txt from wiki/llms.txt plus page sources.

llms-full.txt is the companion convention to llms.txt: the same table of
contents, with the full Markdown of each linked page inlined below it, so a
client can read the whole corpus from one file. This script keeps it
generated, never hand-maintained: it parses the link list in wiki/llms.txt,
maps each site URL to its wiki/*.md source, and concatenates.

Usage:
    python3 tools/generate_llms_full.py          # write wiki/llms-full.txt
    python3 tools/generate_llms_full.py --check  # exit 1 if stale (CI)

Only stdlib. Deterministic output.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
WIKI = REPO / "wiki"
LLMS = WIKI / "llms.txt"
FULL = WIKI / "llms-full.txt"
SITE = "https://linstabpy.vercel.app"

# Site path -> wiki source, for every in-site link in llms.txt.
# External links (github.com, ...) are skipped: header only, no inline body.
PAGE_MAP = {
    "/getting-started/": "getting-started/index.md",
    "/boundaries/": "boundaries.md",
    "/core-concepts/": "core-concepts.md",
    "/faq/": "faq.md",
    "/overview/": "overview.md",
    "/architecture/": "architecture.md",
    "/workflow/": "workflow.md",
    "/modules/": "modules/index.md",
    "/solver-glossary/": "solver-glossary.md",
    "/references/": "references.md",
}

_LINK_RE = re.compile(r"^- \[([^\]]+)\]\(([^)]+)\)(?::\s*(.*))?$")


def _parse_links(text: str) -> list[tuple[str, str, str]]:
    """Return (title, url, note) for each file-list entry in llms.txt."""
    entries = []
    for line in text.splitlines():
        m = _LINK_RE.match(line.strip())
        if m:
            entries.append((m.group(1), m.group(2), m.group(3) or ""))
    return entries


def _read_source(rel: str) -> str:
    src = WIKI / rel
    if not src.is_file():
        raise FileNotFoundError(f"llms-full source missing: {src}")
    body = src.read_text(encoding="utf-8").rstrip() + "\n"
    # Strip YAML frontmatter: not useful inline, breaks the flow.
    if body.startswith("---\n"):
        end = body.find("\n---\n", 4)
        if end != -1:
            body = body[end + 5 :]
    return body


def build() -> str:
    toc = LLMS.read_text(encoding="utf-8").rstrip() + "\n"
    entries = _parse_links(toc)
    if not entries:
        raise SystemExit("no link entries found in wiki/llms.txt")
    parts = [
        toc,
        "\n---\n",
        "# Full content\n",
        "\nThe pages linked above, inlined in order. "
        "Generated by tools/generate_llms_full.py — do not edit.\n",
    ]
    for title, url, _note in entries:
        parts.append(f"\n---\n\n## {title}\n\nSource: {url}\n\n")
        if url.startswith(SITE):
            path = url[len(SITE) :]
            rel = PAGE_MAP.get(path)
            if rel is None:
                raise SystemExit(
                    f"llms.txt links {url} with no PAGE_MAP entry; "
                    "add it to tools/generate_llms_full.py"
                )
            parts.append(_read_source(rel))
        else:
            parts.append(f"(External page; fetch {url} directly.)\n")
    return "".join(parts)


def main(argv: list[str]) -> int:
    check = "--check" in argv
    content = build()
    if check:
        if not FULL.is_file():
            print("wiki/llms-full.txt missing; run tools/generate_llms_full.py")
            return 1
        if FULL.read_text(encoding="utf-8") != content:
            print("wiki/llms-full.txt is stale; run tools/generate_llms_full.py")
            return 1
        print("wiki/llms-full.txt is in sync.")
        return 0
    FULL.write_text(content, encoding="utf-8")
    print(f"wrote {FULL} ({len(content)} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
