"""Regenerate references/generated/*.md from linstabpy source of truth.

Parses (never imports: no PETSc/MPI needed):
  src/linstabpy/config/schema.py  -> TOP_LEVEL_ALLOWED (+ fd orders)
  src/linstabpy/__init__.py       -> _LAZY_EXPORTS
  src/linstabpy/driver/payload.py -> RUNTIME_NPZ_CONTRACT_KEYS

Usage:
    python3 skills/linstabpy/scripts/generate_skill_refs.py          # write files
    python3 skills/linstabpy/scripts/generate_skill_refs.py --check  # exit 1 if stale (CI)

Only stdlib. Deterministic output.
"""

from __future__ import annotations

import ast
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[3]
GEN = REPO / "skills" / "linstabpy" / "references" / "generated"

HEADER = "<!-- Generated by scripts/generate_skill_refs.py -- do not edit. -->\n\n"


def _eval(node: ast.AST):
    """Evaluate simple literal AST (constants, tuples, lists, sets, dicts, frozenset)."""
    if isinstance(node, ast.Constant):
        return node.value
    if isinstance(node, (ast.Tuple, ast.List)):
        return [_eval(e) for e in node.elts]
    if isinstance(node, ast.Set):
        return [_eval(e) for e in node.elts]
    if isinstance(node, ast.Dict):
        return {_eval(k): _eval(v) for k, v in zip(node.keys, node.values)}
    if (
        isinstance(node, ast.Call)
        and isinstance(node.func, ast.Name)
        and node.func.id == "frozenset"
        and len(node.args) == 1
    ):
        return _eval(node.args[0])
    raise ValueError(f"unsupported AST node: {ast.dump(node)[:120]}")


def _load_assign(path: Path, name: str):
    tree = ast.parse(path.read_text(encoding="utf-8"))
    for node in tree.body:
        if isinstance(node, ast.Assign):
            for target in node.targets:
                if isinstance(target, ast.Name) and target.id == name:
                    return _eval(node.value)
        elif isinstance(node, ast.AnnAssign):
            target = node.target
            if isinstance(target, ast.Name) and target.id == name and node.value is not None:
                return _eval(node.value)
    raise SystemExit(f"{name} not found in {path}")


def _yaml_keys() -> str:
    schema = REPO / "src" / "linstabpy" / "config" / "schema.py"
    allowed = sorted(_load_assign(schema, "TOP_LEVEL_ALLOWED"))
    fd_orders = sorted(_load_assign(schema, "_ALLOWED_FD_ORDERS"))
    lines = [
        HEADER,
        "# YAML top-level keys (generated)\n",
        "\nSource: `src/linstabpy/config/schema.py` (`TOP_LEVEL_ALLOWED`).\n",
        "Any other top-level key fails `validate_config`.\n",
        f"\nSBP `fd_order` values allowed: {', '.join(str(o) for o in fd_orders)}.\n",
        f"\nTotal keys: {len(allowed)}.\n\n",
    ]
    for key in allowed:
        lines.append(f"- `{key}`\n")
    return "".join(lines)


_API_BLURBS = {
    "build_lnse_system": "Assemble L0 + index map + BC indices (LNSESystem handoff).",
    "build_lnse_operator": "Assemble the raw sparse LNSE operator only.",
    "compute_chu_norm": "Chu compressible energy inner product (diagonal weights).",
    "temporal_eigenvalues": "SLEPc temporal EVP: omega = eig(i*L0).",
    "adjoint_eigenvalues": "Adjoint temporal EVP for sensitivity.",
    "wavemaker": "Structural sensitivity from direct + adjoint modes.",
    "resolvent_analysis": "Leading gain/forcing/response at one (beta, omega).",
    "resolvent_map": "Frequency walk with anchor factorization reuse.",
    "BaseFlow": "Mean flow, sponge damping, viscosity.",
}


def _python_api() -> str:
    init = REPO / "src" / "linstabpy" / "__init__.py"
    exports = _load_assign(init, "_LAZY_EXPORTS")
    lines = [
        HEADER,
        "# Lazy Python API (generated)\n",
        "\nSource: `src/linstabpy/__init__.py` (`_LAZY_EXPORTS`).\n",
        "Plain `import linstabpy` starts neither PETSc nor MPI; each name "
        "loads from its module on first use and is cached.\n",
        f"\nTotal names: {len(exports)}.\n",
        "\n| Public name | Module | Attribute | What it is |\n",
        "|---|---|---|---|\n",
    ]
    for name in sorted(exports):
        module, attr = exports[name]
        blurb = _API_BLURBS.get(name, "")
        lines.append(f"| `{name}` | `{module}` | `{attr}` | {blurb} |\n")
    return "".join(lines)


_NPZ_GROUPS = (
    ("core", "Core spectrum / fields (no prefix)"),
    ("resolvent_", "Resolvent provenance"),
    ("stability_", "Stability solver + acceptance"),
    ("numerics_", "Operator dissipation policy"),
    ("solver_", "Solver routing"),
    ("provenance_", "Provenance"),
    ("cost_", "Cost / hardware"),
    ("bc_", "Boundary-condition indices"),
    ("git_", "Git provenance"),
)


def _npz_keys() -> str:
    payload = REPO / "src" / "linstabpy" / "driver" / "payload.py"
    keys = list(_load_assign(payload, "RUNTIME_NPZ_CONTRACT_KEYS"))
    grouped: dict[str, list[str]] = {g: [] for g, _ in _NPZ_GROUPS}
    for key in keys:
        for prefix, _ in _NPZ_GROUPS:
            if prefix == "core":
                continue
            if key.startswith(prefix):
                grouped[prefix].append(key)
                break
        else:
            grouped["core"].append(key)
    lines = [
        HEADER,
        "# NPZ contract keys (generated)\n",
        "\nSource: `src/linstabpy/driver/payload.py` (`RUNTIME_NPZ_CONTRACT_KEYS`).\n",
        "Additive keys are fine; renames/removals need a migration note + "
        "test + reader updates (`docs/runtime_npz_contract.md`).\n",
        f"\nTotal keys: {len(keys)}.\n",
    ]
    for prefix, title in _NPZ_GROUPS:
        members = grouped[prefix]
        if not members:
            continue
        lines.append(f"\n## {title} ({len(members)})\n\n")
        for key in members:
            lines.append(f"- `{key}`\n")
    return "".join(lines)


def build_all() -> dict[str, str]:
    return {
        "yaml-keys.md": _yaml_keys(),
        "python-api.md": _python_api(),
        "npz-keys.md": _npz_keys(),
    }


def main(argv: list[str]) -> int:
    check = "--check" in argv
    files = build_all()
    if check:
        stale = [
            name
            for name, content in files.items()
            if not (GEN / name).is_file() or (GEN / name).read_text(encoding="utf-8") != content
        ]
        if stale:
            print(f"stale generated skill refs: {', '.join(stale)}; regenerate")
            return 1
        print("generated skill refs are in sync.")
        return 0
    GEN.mkdir(parents=True, exist_ok=True)
    for name, content in files.items():
        (GEN / name).write_text(content, encoding="utf-8")
        print(f"wrote {GEN / name} ({len(content)} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
