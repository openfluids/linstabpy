#!/usr/bin/env python3
"""Collects per-point outputs into the run-record CSV.

Produces a CSV in the same layout as ``savarino_map3_200pt.csv``,
the 200-point resolvent gain map (supplement figure S6). Two input modes:

1. **Slurm campaign tree** (default): parse ``slurm-*.out`` logs under each
   point directory generated by ``gen_campaign.py``.

2. **NPZ tree** (``--from-npz``): read ``sav_map_*/sav_map_*.npz`` plus optional
   ``.metrics.json`` for a point list from ``--points-csv``.

Run:
    python collect_campaign.py results/campaign [machine_label] > results/campaign.csv
    python collect_campaign.py --from-npz /path/to/resolvent_map_repo_dense \\
        --points-csv configs/savarino_map317_points.csv \\
        --out output/savarino_map317pt.csv merged

Every row carries its own provenance (commit SHA, machine, ranks, backend,
the forcing restriction P, epsilon, DOF, nnz) so it stays meaningful when
copied out of the repository.

Points that have not finished, or that failed, are reported with status !=
"ok" rather than silently omitted: a map with holes in it must say where
the holes are.
"""

from __future__ import annotations

import argparse
import csv
import json
import re
import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent

PAT = {
    "gain": re.compile(r"leading gain\s*:\s*([0-9eE.+-]+)"),
    "resid": re.compile(r"resolvent residual \(fwd, adj\)\s*:\s*([0-9eE.+-]+),\s*([0-9eE.+-]+)"),
    "wall": re.compile(r"compute finished in ([0-9.]+)s"),
    "rss": re.compile(r"peak RSS \[bytes\]\s*:\s*([0-9]+)"),
    "ndof": re.compile(r"ndof\s*:\s*([0-9]+)"),
    # Anchored to the assembly line: a bare `nnz=` also matches `sponge_nnz=`.
    "nnz": re.compile(r"operator assembled with BCs:.*?nnz=([0-9]+)"),
    "hdr": re.compile(r"SHA=(\S+)\s+BETA=(\S+)\s+F=(\S+)"),
    "eps": re.compile(r"epsilon -> resolvent \(effective\)\s*:\s*([0-9eE.+-]+)"),
}

DIRPAT = re.compile(r"sav_map2?_b(?P<b>[0-9p]+)_f(?P<f>[0-9pm]+)(?P<suffix>_[A-Za-z]+)?$")


def backend_of(point_dir: Path) -> tuple[str, int]:
    """(backend, ranks) for a point directory, read from the job's own files.

    ``<root>/<stem>.sbatch`` carries ``#SBATCH --ntasks=N`` and
    ``<root>/configs/<stem>.yaml`` the resolvent solver block ("mumps", or
    "iterative/strumpack" for FGMRES around a STRUMPACK LU -- the GPU arm), so
    the row says what actually ran. Without those files fall back to the
    directory name: a '_GPU' suffix marks a STRUMPACK/GPU variant at 1 rank,
    anything else MUMPS at the CPU default of 4. A row that claimed MUMPS on
    the CPU rank count for a GPU point would be false provenance in a file
    whose whole purpose is that each row describes its own run.
    """
    point_dir = Path(point_dir)
    name = point_dir.name
    backend, ranks = ("strumpack", 1) if name.endswith("_GPU") else ("mumps", 4)
    sbatch = point_dir.parent / f"{name}.sbatch"
    if sbatch.is_file():
        m = re.search(r"^#SBATCH --ntasks=(\d+)", sbatch.read_text(errors="replace"), re.M)
        if m:
            ranks = int(m.group(1))
    config = point_dir.parent / "configs" / f"{name}.yaml"
    if config.is_file():
        try:
            import yaml

            solver = (yaml.safe_load(config.read_text()) or {}).get("solver") or {}
        except Exception:  # noqa: BLE001 - provenance falls back to the name rule
            solver = {}
        res = solver.get("resolvent") or {}
        solver_type = str(res.get("type") or "mumps").lower()
        factor = str(res.get("factor_backend") or solver.get("factor_backend") or "").lower()
        if solver_type in ("mumps", "direct", "lu"):
            backend = factor or solver_type
        else:
            backend = f"{solver_type}/{factor}" if factor else solver_type
    return backend, ranks


def gpu_peak_mib(point_dir: Path) -> str:
    """Peak device memory (MiB) from the job's ``nvsmi.<job>.log`` sampler, or ''."""
    peak = None
    for log in Path(point_dir).glob("nvsmi.*.log"):
        for line in log.read_text(errors="replace").splitlines():
            parts = [x.strip() for x in line.split(",")]
            if len(parts) >= 2:
                try:
                    used = int(float(parts[1]))
                except ValueError:
                    continue
                peak = used if peak is None else max(peak, used)
    return "" if peak is None else str(peak)


def point_from_dirname(name: str) -> tuple[float | None, float | None]:
    """Recover (beta, f) from the directory name so an unfinished point is still
    identifiable in the CSV. The generator encodes '.' as 'p' and '-' as 'm'."""
    m = DIRPAT.match(name)
    if m is None:
        return None, None

    def un(s: str) -> float | None:
        try:
            return float(s.replace("p", ".").replace("m", "-"))
        except ValueError:
            return None

    return un(m.group("b")), un(m.group("f"))


HEADER = (
    "beta_Xsh,f_Xsh_Uinf,gain,rho_fwd,rho_adj,status,wall_s,peak_rss_bytes,ndof,nnz,"
    "epsilon,stride,fd_order,sponge,forcing_norm,response_norm,P_vars,P_x_min,P_x_max,"
    "P_y_max,mask_bc_forcing,ranks,backend,git_sha,slurm_job,machine,gpu_peak_mib"
)


def tag(v: float) -> str:
    return str(v).replace(".", "p").replace("-", "m").replace("+", "")


def run_id(beta: float, f: float) -> str:
    return f"sav_map_b{tag(beta)}_f{tag(f)}"


def _x_max(f: float) -> float:
    return 1.9470833 if (f == 0 or f >= 2) else 1.7954167


def _format_row(
    *,
    beta: float,
    f: float,
    gain: str = "",
    rho_fwd: str = "",
    rho_adj: str = "",
    status: str,
    wall_s: str = "",
    peak_rss: str = "",
    ndof: str = "",
    nnz: str = "",
    epsilon: str = "",
    stride: str = "1",
    fd_order: str = "4",
    sponge: str = "false",
    ranks: str = "4",
    backend: str = "mumps",
    git_sha: str = "",
    slurm_job: str = "",
    machine: str = "",
    gpu_peak_mib: str = "",
) -> str:
    x_max = _x_max(f)
    return (
        f"{beta},{f},{gain},{rho_fwd},{rho_adj},{status},{wall_s},{peak_rss},"
        f"{ndof},{nnz},{epsilon},{stride},{fd_order},{sponge},l2,chu,"
        f"u|v|w,0.20291667,{x_max},0.29627645,true,{ranks},{backend},{git_sha},"
        f"{slurm_job},{machine},{gpu_peak_mib}"
    )


def _load_points_csv(path: Path) -> list[tuple[float, float]]:
    rows = list(csv.DictReader(path.open(encoding="utf-8")))
    if not rows:
        raise SystemExit(f"empty points csv: {path}")
    pts: list[tuple[float, float]] = []
    for row in rows:
        beta = float(row["beta_Xsh"])
        f = float(row["f_Xsh_Uinf"])
        pts.append((beta, f))
    return pts


def _sigma1_from_npz(path: Path) -> float | None:
    try:
        data = np.load(path, allow_pickle=False)
    except (OSError, ValueError):
        return None
    if "gains" in data.files and data["gains"].size:
        return float(np.asarray(data["gains"]).reshape(-1)[0])
    if "sigma1" in data.files and data["sigma1"].size:
        return float(np.asarray(data["sigma1"]).reshape(-1)[0])
    return None


def collect_from_npz(
    *,
    npz_root: Path,
    points: list[tuple[float, float]],
    machine: str,
) -> tuple[list[str], list[str]]:
    ok_rows: list[str] = []
    bad_rows: list[str] = []
    for beta, f in points:
        rid = run_id(beta, f)
        point_dir = npz_root / rid
        npz = point_dir / f"{rid}.npz"
        metrics = point_dir / f"{rid}.metrics.json"
        if not npz.is_file():
            bad_rows.append(
                _format_row(beta=beta, f=f, status="missing", machine=machine)
            )
            print(f"# missing npz: {npz}", file=sys.stderr)
            continue

        gain = _sigma1_from_npz(npz)
        if gain is None:
            bad_rows.append(
                _format_row(beta=beta, f=f, status="no_gain", machine=machine)
            )
            print(f"# no gain in {npz}", file=sys.stderr)
            continue

        meta: dict = {}
        if metrics.is_file():
            meta = json.loads(metrics.read_text(encoding="utf-8"))

        with np.load(npz, allow_pickle=False) as data:
            rho_fwd = ""
            rho_adj = ""
            if "resolvent_rho_fwd" in data.files:
                rho_fwd = str(float(np.asarray(data["resolvent_rho_fwd"]).reshape(-1)[0]))
            if "resolvent_rho_adj" in data.files:
                rho_adj = str(float(np.asarray(data["resolvent_rho_adj"]).reshape(-1)[0]))
            epsilon = ""
            if "numerics_operator_dissipation_epsilon" in data.files:
                epsilon = str(float(np.asarray(data["numerics_operator_dissipation_epsilon"]).reshape(-1)[0]))
            fd_order = str(int(np.asarray(data["fd_order"]).reshape(-1)[0])) if "fd_order" in data.files else "4"
            stride = str(int(np.asarray(data["stride_ksi"]).reshape(-1)[0])) if "stride_ksi" in data.files else "1"
            sponge = "false"
            if "sponge_enabled" in data.files:
                sponge = "true" if bool(np.asarray(data["sponge_enabled"]).reshape(-1)[0]) else "false"
            ndof = str(int(np.asarray(data["ndof"]).reshape(-1)[0])) if "ndof" in data.files else ""
            nnz = str(int(np.asarray(data["nnz"]).reshape(-1)[0])) if "nnz" in data.files else ""

        wall_s = ""
        peak_rss = ""
        ranks = "4"
        git_sha = ""
        if meta:
            wall_s = str(meta.get("cost_wall_total_s", ""))
            peak_rss = str(meta.get("cost_peak_rss_bytes", ""))
            ranks = str(meta.get("cost_mpi_ranks", meta.get("mpi_ranks", 4)))
            git_sha = str(meta.get("git_sha", meta.get("provenance_linstabpy_git_sha", "")))[:7]
            if git_sha in ("", "unknown"):
                git_sha = ""

        ok_rows.append(
            _format_row(
                beta=beta,
                f=f,
                gain=f"{gain:.6g}",
                rho_fwd=rho_fwd,
                rho_adj=rho_adj,
                status="ok",
                wall_s=wall_s,
                peak_rss=peak_rss,
                ndof=ndof,
                nnz=nnz,
                epsilon=epsilon,
                stride=stride,
                fd_order=fd_order,
                sponge=sponge,
                ranks=ranks,
                backend="mumps",
                git_sha=git_sha,
                machine=machine,
            )
        )
    return ok_rows, bad_rows


def collect_from_slurm(*, root: Path, machine: str) -> tuple[list[str], list[str]]:
    ok_rows: list[str] = []
    bad_rows: list[str] = []
    for d in sorted(p for p in root.glob("sav_map*_b*") if p.is_dir()):
        outs = sorted(d.glob("slurm-*.out"))
        if not outs:
            beta, f = point_from_dirname(d.name)
            if beta is None or f is None:
                print(f"# incomplete: {d.name} -> not_started (unparsed name)", file=sys.stderr)
                continue
            bad_rows.append(_format_row(beta=beta, f=f, status="not_started", machine=machine))
            print(f"# incomplete: {d.name} -> not_started", file=sys.stderr)
            continue
        out = outs[-1]
        job = out.stem.split("-")[-1]
        txt = out.read_text(errors="replace")

        h = PAT["hdr"].search(txt)
        if h is None:
            beta, f = point_from_dirname(d.name)
            if beta is None or f is None:
                print(f"# incomplete: {d.name} -> no_header (unparsed name)", file=sys.stderr)
                continue
            bad_rows.append(
                _format_row(
                    beta=beta,
                    f=f,
                    status="no_header",
                    machine=machine,
                    slurm_job=job,
                )
            )
            print(f"# incomplete: {d.name} -> no_header", file=sys.stderr)
            continue
        sha, beta, f = h.group(1)[:7], float(h.group(2)), float(h.group(3))

        g = PAT["gain"].search(txt)
        w = PAT["wall"].search(txt)
        if g is None or w is None:
            err = (d / out.name.replace(".out", ".err")).read_text(errors="replace")[-200:]
            status = "failed" if "Error" in err or "Traceback" in err else "running"
            backend, ranks = backend_of(d)
            bad_rows.append(
                _format_row(
                    beta=beta,
                    f=f,
                    status=status,
                    ranks=str(ranks),
                    backend=backend,
                    git_sha=sha,
                    slurm_job=job,
                    machine=machine,
                )
            )
            print(f"# incomplete: {d.name} -> {status}", file=sys.stderr)
            continue

        r = PAT["resid"].search(txt)
        rss = PAT["rss"].search(txt)
        ndof = PAT["ndof"].search(txt)
        nnz = PAT["nnz"].search(txt)
        eps = PAT["eps"].search(txt)
        backend, ranks = backend_of(d)
        ok_rows.append(
            _format_row(
                beta=beta,
                f=f,
                gain=g.group(1),
                rho_fwd=r.group(1) if r else "",
                rho_adj=r.group(2) if r else "",
                status="ok",
                wall_s=w.group(1),
                peak_rss=rss.group(1) if rss else "",
                ndof=ndof.group(1) if ndof else "",
                nnz=nnz.group(1) if nnz else "",
                epsilon=eps.group(1) if eps else "",
                ranks=str(ranks),
                backend=backend,
                git_sha=sha,
                slurm_job=job,
                machine=machine,
                gpu_peak_mib=gpu_peak_mib(d),
            )
        )
    return ok_rows, bad_rows


def _write_csv(path: Path | None, ok_rows: list[str], bad_rows: list[str]) -> None:
    lines = [HEADER, *ok_rows, *bad_rows]
    text = "\n".join(lines) + "\n"
    if path is None:
        print(text, end="")
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    print(f"wrote {path} ({len(ok_rows)} ok, {len(bad_rows)} incomplete)", file=sys.stderr)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("campaign_root", nargs="?", default="results/campaign", help="Slurm campaign root")
    ap.add_argument("machine", nargs="?", default="", help="machine label for provenance")
    ap.add_argument("--from-npz", type=Path, default=None, help="NPZ campaign root (Savarino2026 layout)")
    ap.add_argument(
        "--points-csv",
        type=Path,
        default=HERE / "configs" / "savarino_map317_points.csv",
        help="(beta, f) list for --from-npz",
    )
    ap.add_argument(
        "--out",
        type=Path,
        default=None,
        help="write CSV here (default: stdout)",
    )
    args = ap.parse_args()

    if args.from_npz is not None:
        points = _load_points_csv(args.points_csv.expanduser().resolve())
        ok_rows, bad_rows = collect_from_npz(
            npz_root=args.from_npz.expanduser().resolve(),
            points=points,
            machine=args.machine,
        )
    else:
        ok_rows, bad_rows = collect_from_slurm(
            root=Path(args.campaign_root).expanduser().resolve(),
            machine=args.machine,
        )
    _write_csv(args.out, ok_rows, bad_rows)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
